#!/usr/bin/env python3
"""Print the toil and churn signals of a Git repository.

The script reads the Git history of one ref. It changes nothing in the
repository. It needs Python 3.9 or later and git. It uses no other package.

    churn.py [--repo DIR] [--ref REF] [--since DATE] [--top N]
             [--generated GLOB ...] [--no-simulate]

Each section of the output is a signal, not a finding. A person or an agent
must read the commits behind a number before it becomes a finding.
"""

from __future__ import annotations

import argparse
import collections
import fnmatch
import itertools
import re
import subprocess
import sys
import tempfile
from pathlib import Path

# A commit that touches more files than this is a bulk move or a format run.
# It says nothing about which files change together.
BULK_COMMIT_FILES = 60
# The conflict simulation replays each change of a file on the file as it was
# this number of changes earlier.
SIM_DISTANCE = 3
SIM_FILES = 15
SIM_COMMITS = 40
LONG_LINE_BYTES = 500

SUBJECT_SIGNALS = {
    "fix": r"\bfix(es|ed)?\b",
    "revert": r"\brevert",
    "again / once more": r"\bagain\b|\bonce more\b|\bre-?do\b",
    "follow-up / review": r"follow-?up|\breview\b|\bnits?\b",
    "flaky / race / timeout": r"flak|\brace\b|\btimeouts?\b|\bslow\b|deadlock|\bretry\b",
    "conflict / merge / rebase": r"conflict|\bmerge\b|rebase",
    "regenerate / golden / snapshot": r"regenerat|\bgolden\b|snapshot",
    "lint / format": r"\blint|\bfmt\b|\bformat\b",
    "ci / workflow": r"^ci\b|\bci:|\bworkflows?\b",
    "bump / pin / upgrade": r"\bbump|\bpin\b|upgrade",
    "move / rename / split": r"\bmove|\brename|\bsplit\b",
    "remove / drop": r"\bremove|\bdrop\b|\bdelete",
    "plan kept in line with the code": r"against main|match(es)? main|align|\bstale\b|out of date|\bsync\b",
}

# Markers that switch a check off for one line or one file.
SUPPRESSIONS = [
    "//[[:space:]]*nolint:[a-z0-9_,-]+", "nosemgrep", "eslint-disable[a-z-]*",
    "@ts-(ignore|expect-error)", "#[[:space:]]*noqa", "#[[:space:]]*type:[[:space:]]*ignore",
    "#\\[allow\\([a-z_:]+\\)", "@SuppressWarnings", "rubocop:disable",
]

CONFIG_RE = re.compile(
    r"^(\.[^/]+|Makefile|Justfile|Taskfile\.ya?ml|Dockerfile[^/]*|[^/]+\.(ya?ml|toml|json|cfg|ini|mod|lock)"
    r"|\.github/.+|\.circleci/.+|scripts/.+|[^/]*(AGENTS|CLAUDE|CONTRIBUTING)\.md)$"
)
GENERATED_PATH_RE = re.compile(
    r"(^|/)(testdata|__snapshots__|golden|vendor|node_modules|dist|gen|generated)/"
    r"|\.(golden|snap|lock|pb\.go|min\.js)$|(^|/)(go\.sum|package-lock\.json|pnpm-lock\.yaml|yarn\.lock)$"
)
GENERATED_HEADER_RE = re.compile(r"Code generated .* DO NOT EDIT|@generated|DO NOT EDIT|Do not edit this file", re.I)
DOC_RE = re.compile(r"\.(md|mdx|rst|adoc|txt)$")

REPO = Path(".")


def git(*args: str, check: bool = True) -> str:
    """Run git with an argument list and return its output."""
    done = subprocess.run(
        ["git", "-C", str(REPO), *args], capture_output=True, text=True, errors="replace", check=False
    )
    if done.returncode != 0:
        if check:
            sys.exit(f"churn: git {args[0]} failed: {done.stderr.strip()}")
        return ""
    return done.stdout


def git_bytes(*args: str) -> bytes | None:
    done = subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, check=False)
    return done.stdout if done.returncode == 0 else None


def section(title: str) -> None:
    print(f"\n## {title}\n")


def percentile(values: list[int], share: float) -> int:
    return values[min(len(values) - 1, int(len(values) * share))] if values else 0


def prefix(path: str, depth: int = 2) -> str:
    parts = path.split("/")
    return "/".join(parts[:depth]) if len(parts) > depth else (str(Path(path).parent) if len(parts) > 1 else ".")


def simulate(ref: str, since: list[str], path: str) -> tuple[int, int]:
    """Count the changes of path that conflict with the changes just before them.

    For each commit C on the file: base is the file before C, theirs is the
    file after C, and ours is the file SIM_DISTANCE changes earlier. A line
    merge that fails shows that C and the changes just before it could not be
    open at the same time. The result is (conflicts, merges tried).
    """
    shas = git("log", ref, "--no-merges", "--reverse", "--format=%H", *since, "--", path).split()[-SIM_COMMITS:]
    conflicts = tried = 0
    with tempfile.TemporaryDirectory() as tmp:
        for i in range(SIM_DISTANCE, len(shas)):
            versions = {
                "theirs": git_bytes("show", f"{shas[i]}:{path}"),
                "base": git_bytes("show", f"{shas[i]}^:{path}"),
                "ours": git_bytes("show", f"{shas[i - SIM_DISTANCE]}^:{path}"),
            }
            if any(v is None for v in versions.values()):
                continue
            for name, data in versions.items():
                (Path(tmp) / name).write_bytes(data or b"")
            done = subprocess.run(
                ["git", "merge-file", "-p", f"{tmp}/ours", f"{tmp}/base", f"{tmp}/theirs"],
                capture_output=True, check=False,
            )
            tried += 1
            conflicts += 1 if done.returncode != 0 else 0
    return conflicts, tried


def main() -> None:
    global REPO
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--repo", default=".", type=Path)
    parser.add_argument("--ref", default="HEAD", help="the default branch, for example origin/main")
    parser.add_argument("--since", default=None, help="for example '3 months ago'")
    parser.add_argument("--top", default=25, type=int)
    parser.add_argument("--generated", action="append", default=[], metavar="GLOB",
                        help="a path pattern of generated files; repeat the option for more")
    parser.add_argument("--no-simulate", action="store_true", help="skip the conflict simulation")
    args = parser.parse_args()
    REPO, top, ref = args.repo, args.top, args.ref
    since = [f"--since={args.since}"] if args.since else []

    if git("rev-parse", "--is-shallow-repository").strip() == "true":
        print("WARNING: this clone is shallow. The numbers cover only a part of the history.")
        print("Run `git fetch --unshallow` (or `git fetch --deepen=5000 origin <branch>`) and start again.")

    # Dates are commit dates, because --since selects by commit date.
    commits: list[dict] = []
    log = git("log", ref, "--no-merges", "--no-renames", "--numstat", "--date=short", "--format=@%h\t%cd\t%an\t%s", *since)
    for line in log.splitlines():
        if line.startswith("@"):
            sha, day, author, subject = line[1:].split("\t", 3)
            commits.append({"sha": sha, "day": day, "author": author, "subject": subject, "files": {}})
        elif line.strip() and commits:
            added, deleted, path = line.split("\t", 2)
            commits[-1]["files"][path] = 0 if added == "-" else int(added) + int(deleted)
    if not commits:
        sys.exit("churn: no commits in this range")
    commits.reverse()  # oldest first
    start = git("rev-parse", f"{commits[0]['sha']}^", check=False).strip()  # the tree before the range

    tracked = set(git("ls-tree", "-r", "--name-only", ref).splitlines())
    touches = collections.Counter(path for c in commits for path in c["files"])
    days = sorted({c["day"] for c in commits})
    half = len(commits) // 2
    second_half = collections.Counter(path for c in commits[half:] for path in c["files"])

    # Generated files: the patterns of the caller, .gitattributes, usual paths, and the file header.
    patterns = list(args.generated)
    for line in git("show", f"{ref}:.gitattributes", check=False).splitlines():
        if "linguist-generated" in line and not line.lstrip().startswith("#"):
            patterns.append(line.split()[0])
    header_cache: dict[str, bool] = {}

    def is_generated(path: str) -> bool:
        if GENERATED_PATH_RE.search(path) or any(fnmatch.fnmatch(path, p.replace("/**", "/*")) for p in patterns):
            return True
        if path not in header_cache:
            head = git_bytes("show", f"{ref}:{path}") if path in tracked else None
            header_cache[path] = bool(head and GENERATED_HEADER_RE.search(head[:600].decode(errors="ignore")))
        return header_cache[path]

    section("Overview")
    per_day = collections.Counter(c["day"] for c in commits)
    sizes = sorted(len(c["files"]) for c in commits)
    merges = len(git("log", ref, "--merges", "--format=%h", *since).split())
    print(f"- commits: {len(commits)} from {days[0]} to {days[-1]} on {len(days)} active days (commit dates)")
    print(f"- busiest day: {per_day.most_common(1)[0][1]} commits; median day: {percentile(sorted(per_day.values()), 0.5)}")
    print(f"- files in one commit: median {percentile(sizes, 0.5)}, p90 {percentile(sizes, 0.9)}, max {sizes[-1]}")
    authors = collections.Counter(c["author"] for c in commits)
    print("- authors: " + ", ".join(f"{name} ({n})" for name, n in authors.most_common(6)))
    if merges:
        print(f"- merge commits: {merges}. They are not in the counts below. Read their messages for conflicts:")
        print(f"  git log {ref} --merges --grep=Conflicts --format='%h %s'")
    else:
        print("- merge commits: 0. The history is linear (squash or rebase), so it holds no record of a")
        print("  conflict. The section 'Conflict simulation' estimates the conflicts.")

    section("Hot directories")
    print("'only' = commits that change nothing outside the directory. A directory of plans, specs or")
    print("configuration with a high 'only' count is work that makes no product change.\n")
    in_dir: collections.Counter = collections.Counter()
    only_dir: collections.Counter = collections.Counter()
    for c in commits:
        dirs = {prefix(path) for path in c["files"]}
        in_dir.update(dirs)
        if len(dirs) == 1:
            only_dir.update(dirs)
    for directory, n in in_dir.most_common(top // 2):
        print(f"{n:5d} commits ({100 * n / len(commits):2.0f}%), {only_dir[directory]:4d} only  {directory}")

    section("Hot files (commits that touch the file)")
    print("A hot file that many changes must edit is a conflict point. Ask why each change needs it.")
    print("'2nd half' = the commits in the newer half of the range. A low number shows a repair.\n")
    hot_files = touches.most_common(top)
    for path, n in hot_files:
        note = "  [generated]" if is_generated(path) else ""
        if path not in tracked:
            last = git("log", ref, "-1", "--diff-filter=D", "--format=%h %s", "--", path).strip()
            note += f"  [removed by {last[:70]}]"
        print(f"{n:5d} commits, {second_half[path]:4d} in 2nd half  {path}{note}")

    if not args.no_simulate:
        section("Conflict simulation (hand-written hot files)")
        print(f"For each change of a file: does a line merge fail when the file is {SIM_DISTANCE} changes older?")
        print("A high share is a real conflict point. A hot file with a low share is only busy.")
        print(f"This is an estimate. It reads the last {SIM_COMMITS} changes of each file.\n")
        candidates = [p for p, _ in touches.most_common(top * 3) if p in tracked and not is_generated(p)][:SIM_FILES]
        results = []
        for path in candidates:
            conflicts, tried = simulate(ref, since, path)
            if tried >= 5:
                results.append((conflicts / tried, conflicts, tried, path))
        for share, conflicts, tried, path in sorted(results, reverse=True):
            print(f"{100 * share:4.0f}%  {conflicts:3d} of {tried:3d}  {path}")

    section("Files that change together")
    print("share = commits with both files / commits of the less frequent file. A high share between")
    print("hand-written files is one decision that people write in two places. Each file is in the")
    print("list one time, with its strongest partner.\n")
    floor = max(5, len(commits) // 100)
    hot = {path for path, n in touches.items() if n >= floor}
    pairs: collections.Counter = collections.Counter()
    for c in commits:
        if len(c["files"]) > BULK_COMMIT_FILES:
            continue
        for pair in itertools.combinations(sorted(hot & c["files"].keys()), 2):
            pairs[pair] += 1
    rows = sorted(((n / min(touches[a], touches[b]), n, a, b) for (a, b), n in pairs.items() if n >= floor), reverse=True)
    seen: set[str] = set()
    shown = 0
    for share, n, a, b in rows:
        if share < 0.5 or shown >= top:
            break
        if a in seen or b in seen:
            continue
        seen.update((a, b))
        shown += 1
        print(f"{share:.2f} {n:4d}  {a}  <->  {b}")

    section("Rework in one day (commits on one file in one day)")
    print("Many commits on one file in one day show a slow feedback loop or a serial queue on that file.\n")
    same_day = collections.Counter((c["day"], path) for c in commits for path in c["files"])
    for (day, path), n in same_day.most_common(top // 2):
        if n >= 4:
            print(f"{n:4d}  {day}  {path}")

    section("Commit subjects")
    print("The count is the number of subjects that match. A word can be innocent: read more subjects")
    print(f"with `git log {ref} -i -E --grep='<pattern>' --format='%cd %s' --date=short`.\n")
    for name, pattern in SUBJECT_SIGNALS.items():
        matched = [c for c in commits if re.search(pattern, c["subject"], re.I)]
        if not matched:
            continue
        print(f"{len(matched):5d} ({100 * len(matched) / len(commits):.0f}%)  {name}    pattern: {pattern}")
        step = max(1, len(matched) // 5)
        for c in matched[::step][:5]:
            print(f"         {c['day']} {c['subject'][:110]}")
    words = collections.Counter(re.split(r"[:\s(]", c["subject"].lower(), maxsplit=1)[0] for c in commits)
    print("\nMost frequent first words: " + ", ".join(f"{w} ({n})" for w, n in words.most_common(15)))

    section("Configuration, tooling and rule files")
    print("Each change here is work on the workshop and not on the product. Growth of a rule file shows")
    print("that a problem became a rule for people and not a mechanism. 'lines' = at the start of the")
    print("range -> now.\n")
    config = sorted(((n, path) for path, n in touches.items() if CONFIG_RE.match(path)), reverse=True)
    for n, path in config[:top]:
        size = ""
        now = git_bytes("show", f"{ref}:{path}") if path in tracked else None
        if now is not None:
            then = git_bytes("show", f"{start}:{path}") if start else None
            before = "new" if then is None else str(len(then.splitlines()))
            size = f"  lines: {before} -> {len(now.splitlines())}"
        print(f"{n:5d}  {path}{size}")

    section("Where the changed lines go")
    total = generated = docs = 0
    for c in commits:
        for path, lines in c["files"].items():
            total += lines
            if is_generated(path):
                generated += lines
            elif DOC_RE.search(path):
                docs += lines
    if total:
        print(f"- all changed lines: {total}")
        print(f"- generated, golden, snapshot and lock files: {generated} ({100 * generated / total:.0f}%)")
        print(f"- prose (documents, specs, rule files): {docs} ({100 * docs / total:.0f}%)")
        print("The generated share is a lower bound. Give the generated paths of the repository with --generated.")

    section("Long lines in hot files")
    print("Git merges by line. Two changes to one long line always conflict. Look for a list, a digest")
    print("or a whole document on one line.\n")
    for path, n in touches.most_common(100):
        data = git_bytes("show", f"{ref}:{path}") if path in tracked else None
        if data is not None and len(data) < 20_000_000:
            longest = max((len(line) for line in data.splitlines()), default=0)
            if longest > LONG_LINE_BYTES:
                print(f"{n:5d} commits, longest line {longest} bytes  {path}")

    section("Short-lived files (added and deleted in this range, moves not counted)")
    born: set[str] = set()
    died: list[str] = []
    status = git("log", ref, "--no-merges", "--reverse", "-M", "--diff-filter=AD", "--name-status", "--format=", *since)
    for line in status.splitlines():
        if line.startswith("A\t"):
            born.add(line[2:])
        elif line.startswith("D\t") and line[2:] in born:
            died.append(line[2:])
    by_dir = collections.Counter(prefix(path, 3) for path in died)
    print(f"{len(died)} files. Directories with the most:")
    for directory, n in by_dir.most_common(8):
        print(f"{n:5d}  {directory}")

    section("Suppression markers in the tree")
    print("This is a total of the tree, not of the range. A check with many suppressions has the wrong")
    print("configuration for this code.\n")
    found: collections.Counter = collections.Counter()
    marker = "|".join(SUPPRESSIONS)  # POSIX extended syntax, for git grep
    grep = git("grep", "-I", "-o", "-h", "-E", marker, ref, check=False)
    found.update(line.strip() for line in grep.splitlines())
    for name, n in found.most_common(top // 2):
        print(f"{n:5d}  {name}")


if __name__ == "__main__":
    main()
